/// The stage table recorded in snapshots for the Authority Figures stage,
/// which has no table of its own.
pub const FIGURES_STAGE_ID: &str = "stage.authorityFigures";

/// One field of an Authority Figure and the table it is rolled on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FigureFieldDef {
    /// Stable field ID, e.g. `species`.
    pub id: &'static str,
    pub label: &'static str,
    pub table: &'static str,
}

/// The fields of an Authority Figure, rolled in this order.
pub const FIGURE_FIELDS: [FigureFieldDef; 7] = [
    FigureFieldDef {
        id: "species",
        label: "Species",
        table: "table.authorityFigure.species",
    },
    FigureFieldDef {
        id: "gender",
        label: "Gender",
        table: "table.authorityFigure.gender",
    },
    FigureFieldDef {
        id: "age",
        label: "Age",
        table: "table.authorityFigure.age",
    },
    FigureFieldDef {
        id: "disposition",
        label: "Disposition",
        table: "table.authorityFigure.disposition",
    },
    FigureFieldDef {
        id: "motive",
        label: "Motive",
        table: "table.authorityFigure.motive",
    },
    FigureFieldDef {
        id: "reputation",
        label: "Reputation",
        table: "table.authorityFigure.reputation",
    },
    FigureFieldDef {
        id: "flaw",
        label: "Flaw / Complication",
        table: "table.authorityFigure.flaw",
    },
];

/// Rolled once for every unordered pair of figures.
pub const RELATIONSHIP_TABLE: &str = "table.authorityRelationship";

/// The tables the Authority Figures stage needs.
pub fn required_tables() -> impl Iterator<Item = TableId> {
    FIGURE_FIELDS
        .iter()
        .map(|f| TableId::new(f.table))
        .chain(std::iter::once(TableId::new(RELATIONSHIP_TABLE)))
}

fn field_def(id: &str) -> Result<&'static FigureFieldDef, GenerationError> {
    FIGURE_FIELDS
        .iter()
        .find(|f| f.id == id)
        .ok_or_else(|| GenerationError::NoSuchFigureField(id.to_owned()))
}

/// One rolled (or chosen) field of a figure, with its full record.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FigureField {
    /// The field ID from [`FIGURE_FIELDS`].
    pub field: String,
    pub roll: TableRollRecord,
}

/// How a figure got its name.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "source", rename_all = "snake_case")]
pub enum FigureName {
    /// Generated by a person naming scheme; every roll is kept.
    Generated {
        name: String,
        /// The figure's species when it was named: the name's source.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        species: Option<Named<ResultId>>,
        scheme: Named<NamingSchemeId>,
        method: Named<ResultId>,
        /// Each named part (e.g. given name, family name) and its result,
        /// when the naming method describes its parts.
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        parts: Vec<NamePartRecord>,
        /// The method roll, then one roll per component.
        rolls: Vec<TableRollRecord>,
    },
    /// Typed by the user.
    Custom { name: String },
    /// No naming data applies to this figure (e.g. its species has no
    /// naming scheme yet). Nothing is invented; a name can be typed.
    Missing { reason: String },
}

impl FigureName {
    /// The name, unless it is missing.
    pub fn text(&self) -> Option<&str> {
        match self {
            FigureName::Generated { name, .. } | FigureName::Custom { name } => Some(name),
            FigureName::Missing { .. } => None,
        }
    }
}

/// One named part of a generated name, e.g. the given name.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NamePartRecord {
    /// The part ID from the naming method, e.g. `given`.
    pub id: String,
    pub label: String,
    pub result: Named<ResultId>,
}

/// One Authority Figure, as generated.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AuthorityFigure {
    /// Stable for the life of the figure; relationships refer to it.
    pub id: NpcId,
    /// What to call the figure: the name, else "Figure n".
    pub label: String,
    /// The Role / Title allocated before the figure was generated, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub role: Option<FigureRole>,
    /// The fields, in [`FIGURE_FIELDS`] order.
    pub fields: Vec<FigureField>,
    pub name: FigureName,
    /// Tags the figure's own results activated (e.g. `species.human`).
    /// They route the name and are never settlement tags.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tags: Vec<Named<TagId>>,
    /// Application version that generated the figure.
    pub app_version: String,
}

impl AuthorityFigure {
    /// The record of one field, e.g. `species`.
    pub fn field(&self, id: &str) -> Option<&TableRollRecord> {
        self.fields.iter().find(|f| f.field == id).map(|f| &f.roll)
    }
}

/// A figure's Role / Title, from its role allocation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FigureRole {
    pub allocation: Allocation,
    /// The stable role and its neutral title (e.g. "Lord / Lady").
    pub role: Named<ResultId>,
    /// The title as shown for this figure (e.g. "Lady" for a woman).
    pub label: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub label_variants: Vec<LabelVariant>,
}

impl FigureRole {
    fn new(assignment: &RoleAssignment, tags: &[Named<TagId>]) -> Self {
        let mut role = FigureRole {
            allocation: assignment.allocation,
            role: assignment.role.clone(),
            label: String::new(),
            label_variants: assignment.label_variants.clone(),
        };
        role.relabel(tags);
        role
    }

    /// Shows the title for a holder with `tags`.
    fn relabel(&mut self, tags: &[Named<TagId>]) {
        let ids: Vec<TagId> = tags.iter().map(|t| t.id.clone()).collect();
        self.label = LabelVariant::pick(&self.label_variants, &self.role.name, &ids);
    }
}

/// Gives each figure the role at its position (lead first). Titles follow
/// each figure's own tags (e.g. its gender). The counts must match.
pub(crate) fn apply_roles(
    record: &mut AuthorityFigures,
    roles: &[RoleAssignment],
) -> Result<(), GenerationError> {
    if roles.len() != record.figures.len() {
        return Err(GenerationError::RolesDoNotMatch);
    }
    for (figure, assignment) in record.figures.iter_mut().zip(roles) {
        figure.role = Some(FigureRole::new(assignment, &figure.tags));
    }
    Ok(())
}

/// How one pair of figures get on. Recorded once per unordered pair.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Relationship {
    pub a: NpcId,
    pub b: NpcId,
    pub roll: TableRollRecord,
}

/// The Authority Figures of a settlement and their relationships, with
/// every roll: the record saved with the settlement.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AuthorityFigures {
    /// The Authority the figures hold, and how many there are.
    pub request: AuthorityRepresentatives,
    pub figures: Vec<AuthorityFigure>,
    /// One per unordered pair, in order (1–2, 1–3, …, 2–3, …).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub relationships: Vec<Relationship>,
    pub app_version: String,
}

impl AuthorityFigures {
    pub fn figure(&self, id: &NpcId) -> Option<&AuthorityFigure> {
        self.figures.iter().find(|f| &f.id == id)
    }
}

/// Rolls Authority Figures and relationships with shared content and dice.
pub(crate) struct FigureGenerator<'g, 'c> {
    pub generator: &'g Generator<'c>,
    pub content: &'c ContentSet,
    /// Tags active in the settlement before the figures are generated.
    pub settlement_tags: &'g [TagId],
}

impl FigureGenerator<'_, '_> {
    /// Generates `request.size` figures, one relationship per unordered
    /// pair. `roles` gives each figure's Role / Title, by position (lead
    /// first); when given there is exactly one per figure.
    pub fn generate(
        &self,
        request: &AuthorityRepresentatives,
        roles: &[RoleAssignment],
        faces: &mut dyn FaceSource,
    ) -> Result<AuthorityFigures, GenerationError> {
        if !roles.is_empty() && roles.len() != request.size as usize {
            return Err(GenerationError::RolesDoNotMatch);
        }
        let mut figures = Vec::new();
        for i in 0..request.size as usize {
            figures.push(self.figure(NpcId::new_random(), i, roles.get(i), faces)?);
        }
        let mut relationships = Vec::new();
        for i in 0..figures.len() {
            for j in i + 1..figures.len() {
                relationships.push(Relationship {
                    a: figures[i].id.clone(),
                    b: figures[j].id.clone(),
                    roll: self.roll(&TableId::new(RELATIONSHIP_TABLE), &[], None, faces)?,
                });
            }
        }
        Ok(AuthorityFigures {
            request: request.clone(),
            figures,
            relationships,
            app_version: VERSION.to_owned(),
        })
    }

    /// One new figure: every field rolled in order, then the name.
    fn figure(
        &self,
        id: NpcId,
        index: usize,
        role: Option<&RoleAssignment>,
        faces: &mut dyn FaceSource,
    ) -> Result<AuthorityFigure, GenerationError> {
        let mut fields: Vec<FigureField> = Vec::new();
        for def in &FIGURE_FIELDS {
            let own = self.own_tags(&fields);
            fields.push(FigureField {
                field: def.id.to_owned(),
                roll: self.roll(&TableId::new(def.table), &own, None, faces)?,
            });
        }
        let tags = self.named(&self.own_tags(&fields));
        let mut figure = AuthorityFigure {
            id,
            label: String::new(),
            role: role.map(|r| FigureRole::new(r, &tags)),
            tags,
            fields,
            name: FigureName::Missing {
                reason: String::new(),
            },
            app_version: VERSION.to_owned(),
        };
        figure.name = self.name(&figure, None, faces)?;
        figure.label = label(&figure, index);
        Ok(figure)
    }

    /// Rolls (or uses the chosen result of) one field of a figure, keeping
    /// its other fields. A change to the figure's tags (its species or
    /// gender) routes its name afresh, unless the name was typed.
    pub fn set_field(
        &self,
        figure: &mut AuthorityFigure,
        index: usize,
        field: &str,
        choice: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<(), GenerationError> {
        let def = field_def(field)?;
        let others: Vec<FigureField> = figure
            .fields
            .iter()
            .filter(|f| f.field != field)
            .cloned()
            .collect();
        let roll = self.roll(
            &TableId::new(def.table),
            &self.own_tags(&others),
            choice,
            faces,
        )?;
        let before = figure.tags.clone();
        match figure.fields.iter_mut().find(|f| f.field == field) {
            Some(existing) => existing.roll = roll,
            None => figure.fields.push(FigureField {
                field: field.to_owned(),
                roll,
            }),
        }
        figure.tags = self.named(&self.own_tags(&figure.fields));
        if let Some(role) = &mut figure.role {
            role.relabel(&figure.tags);
        }
        let typed = matches!(figure.name, FigureName::Custom { .. });
        if figure.tags != before && !typed {
            figure.name = self.name(figure, None, faces)?;
        }
        figure.label = label(figure, index);
        figure.app_version = VERSION.to_owned();
        Ok(())
    }

    /// Generates the figure's name again with the scheme that applies, or
    /// with `method` chosen from it.
    pub fn rename(
        &self,
        figure: &mut AuthorityFigure,
        index: usize,
        method: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<(), GenerationError> {
        figure.name = self.name(figure, method, faces)?;
        figure.label = label(figure, index);
        Ok(())
    }

    /// Rolls (or uses the chosen result of) one relationship.
    pub fn relationship(
        &self,
        choice: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<TableRollRecord, GenerationError> {
        self.roll(&TableId::new(RELATIONSHIP_TABLE), &[], choice, faces)
    }

    /// Resolves `table` under the settlement's tags plus `own` (the
    /// figure's tags so far), with physical dice or the chosen result.
    fn roll(
        &self,
        table: &TableId,
        own: &[TagId],
        choice: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<TableRollRecord, GenerationError> {
        let mut state = State::with_tags(self.settlement_tags.iter().chain(own));
        self.generator.process(
            &mut state,
            [Request::new(table.clone()).with_choice(choice)].into(),
            &Selections::new(),
            faces,
        )?;
        state
            .take_events()
            .into_iter()
            .find_map(|e| match e {
                GenerationEvent::TableRolled(r) if r.routed_by.is_none() => Some(*r),
                _ => None,
            })
            .ok_or_else(|| GenerationError::FigureTableSkipped {
                table: table.clone(),
            })
    }

    /// The tags a figure's fields activate (not already settlement tags).
    fn own_tags(&self, fields: &[FigureField]) -> Vec<TagId> {
        let emitted: Vec<TagId> = fields
            .iter()
            .flat_map(|f| f.roll.tags.iter().map(|t| t.id.clone()))
            .collect();
        self.generator
            .activation_closure(&emitted)
            .into_iter()
            .filter(|t| !self.settlement_tags.contains(t))
            .collect()
    }

    fn named(&self, tags: &[TagId]) -> Vec<Named<TagId>> {
        tags.iter()
            .map(|id| {
                let name = self
                    .content
                    .tag(id)
                    .map_or_else(|| id.to_string(), |t| t.name.clone());
                Named {
                    id: id.clone(),
                    name,
                }
            })
            .collect()
    }

    /// The figure's name from the person naming scheme its tags select.
    fn name(
        &self,
        figure: &AuthorityFigure,
        method: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<FigureName, GenerationError> {
        let own: Vec<TagId> = figure.tags.iter().map(|t| t.id.clone()).collect();
        let tags: Vec<TagId> = self.settlement_tags.iter().chain(&own).cloned().collect();
        let Some(scheme) = scheme_for_subject(self.content, NamingSubject::Person, &tags) else {
            if method.is_some() {
                return Err(GenerationError::NoNamingScheme);
            }
            return Ok(FigureName::Missing {
                reason: missing_reason(figure),
            });
        };
        let mut state = State::with_tags(&tags);
        let GeneratedName {
            text,
            method,
            rolls,
        } = generate_name(self.generator, scheme, &mut state, method, faces)?;
        let parts = scheme
            .method(&method.id)
            .map(|m| part_records(m, &rolls))
            .unwrap_or_default();
        Ok(FigureName::Generated {
            name: text,
            species: figure.field("species").map(|r| r.result.clone()),
            scheme: Named {
                id: scheme.id.clone(),
                name: scheme.name.clone(),
            },
            method,
            parts,
            rolls,
        })
    }

    /// The scheme and method a generated name came from, as they are in the
    /// content now.
    fn naming_of(
        &self,
        figure: &AuthorityFigure,
    ) -> Result<(&NamingScheme, &NamingMethod), GenerationError> {
        let FigureName::Generated { scheme, method, .. } = &figure.name else {
            return Err(GenerationError::FigureNameNotGenerated);
        };
        let scheme = self
            .content
            .naming_schemes
            .iter()
            .find(|s| s.id == scheme.id)
            .ok_or(GenerationError::NoFigureNamingScheme)?;
        let method = scheme
            .method(&method.id)
            .ok_or(GenerationError::NoFigureNamingScheme)?;
        Ok((scheme, method))
    }

    /// Rolls (or uses the chosen result of) one part of a generated name,
    /// e.g. the given name, keeping the other parts, and joins the name
    /// again with its method's rules.
    pub fn set_name_part(
        &self,
        figure: &mut AuthorityFigure,
        index: usize,
        part: usize,
        choice: Option<ResultId>,
        faces: &mut dyn FaceSource,
    ) -> Result<(), GenerationError> {
        let (_, method) = self.naming_of(figure)?;
        let table = method
            .components
            .get(part)
            .ok_or(GenerationError::NoSuchNamePart { index: part })?;
        let own: Vec<TagId> = figure.tags.iter().map(|t| t.id.clone()).collect();
        let record = self.roll(table, &own, choice, faces)?;
        let FigureName::Generated {
            name, parts, rolls, ..
        } = &mut figure.name
        else {
            return Err(GenerationError::FigureNameNotGenerated);
        };
        let slot = rolls
            .get_mut(part + 1)
            .ok_or(GenerationError::NoSuchNamePart { index: part })?;
        *slot = record;
        let named: Vec<NamePart> = rolls[1..]
            .iter()
            .map(|r| NamePart {
                result: &r.result.id,
                text: &r.result.name,
            })
            .collect();
        *name = method.compose(&named);
        *parts = part_records(method, rolls);
        figure.label = label(figure, index);
        Ok(())
    }

    /// For each part of a figure's generated name, its table and results
    /// under the figure's tags: only the pools its species (and gender)
    /// use. Empty when the name was not generated.
    pub fn name_part_options(&self, figure: &AuthorityFigure) -> Vec<NamePartOptions> {
        let Ok((_, method)) = self.naming_of(figure) else {
            return Vec::new();
        };
        let own: Vec<TagId> = figure.tags.iter().map(|t| t.id.clone()).collect();
        let state = State::with_tags(self.settlement_tags.iter().chain(&own));
        method
            .components
            .iter()
            .enumerate()
            .filter_map(|(i, table)| {
                let (table, options) = self.generator.options_for(table, &state).ok()?;
                let (id, label) = method.parts.get(i).map_or_else(
                    || (format!("part{}", i + 1), table.name.clone()),
                    |p| (p.id.clone(), p.label.clone()),
                );
                Some(NamePartOptions {
                    part: i,
                    id,
                    label,
                    table,
                    options,
                })
            })
            .collect()
    }
}

/// "No name table configured for Dark Elf."
fn missing_reason(figure: &AuthorityFigure) -> String {
    match figure.field("species") {
        Some(species) => format!("No name table configured for {}.", species.result.name),
        None => "No name table configured for this species.".to_owned(),
    }
}

/// The named parts of a generated name, from its component rolls.
fn part_records(method: &NamingMethod, rolls: &[TableRollRecord]) -> Vec<NamePartRecord> {
    method
        .parts
        .iter()
        .zip(rolls.iter().skip(1))
        .map(|(part, roll)| NamePartRecord {
            id: part.id.clone(),
            label: part.label.clone(),
            result: roll.result.clone(),
        })
        .collect()
}

/// One part of a figure's generated name and the results it can take.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NamePartOptions {
    /// Position among the method's components.
    pub part: usize,
    /// The part ID, e.g. `given`.
    pub id: String,
    pub label: String,
    pub table: Named<TableId>,
    pub options: Vec<ResultOption>,
}

/// What to call a figure: its name, else "Figure n" (1-based).
fn label(figure: &AuthorityFigure, index: usize) -> String {
    figure
        .name
        .text()
        .map_or_else(|| format!("Figure {}", index + 1), str::to_owned)
}

/// Sets a typed name, keeping everything else.
pub(crate) fn set_custom_name(figure: &mut AuthorityFigure, index: usize, name: String) {
    figure.name = FigureName::Custom { name };
    figure.label = label(figure, index);
}
